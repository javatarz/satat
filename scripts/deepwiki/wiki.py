#!/usr/bin/env python3
"""Generate or update docs/wiki/ with DeepWiki-Open. Runs inside the
DeepWiki-Open image; scripts/deepwiki/wiki.sh starts it with:

  /repo  this repo, read-only (the code to document)
  /out   docs/wiki, read-write (wiki.json plus one Markdown file per page)

Modes (WIKI_MODE):
  full  plan a new wiki structure, then write every page
  diff  keep the structure in /out/wiki.json and rewrite only the pages that
        cite a file in WIKI_CHANGED (the files changed since the commit that
        wiki was built from, one per line)

Chat and embeddings both go to OpenRouter (OPENROUTER_API_KEY): chat through
DeepWiki's OpenRouter provider, embeddings through its OpenAI client pointed
at OpenRouter's OpenAI-compatible endpoint.

Nothing is written when a page failed, the RAG index is incomplete, or a page
cites a file that does not exist.
"""

import asyncio
import json
import logging
import os
import re
import sys
import tempfile
from pathlib import Path

REPO, OUT, APP = Path("/repo"), Path("/out"), Path("/app")
STATE = OUT / "wiki.json"
OPENROUTER = "https://openrouter.ai/api/v1"
BANNER = "<!-- Generated by DeepWiki-Open (scripts/deepwiki). Do not edit; regenerate with `just wiki`. -->"

# DeepWiki saves a page that failed as an error message instead of failing:
# its placeholder after the retries, and every error of the OpenRouter client.
# The message follows the "Relevant source files" <details> block.
FAILED_PAGE = re.compile(
    r"\s*(<details>.*?</details>\s*)?"
    r"(Error generating content:|Error with \S+ API:|I apologize, but your request is too large"
    r"|OpenRouter API error \(|Connection error with OpenRouter API"
    r"|Unexpected error calling OpenRouter API|Error calling OpenRouter API|Error: .* from OpenRouter API)",
    re.S,
)


def die(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def say(msg: str) -> None:
    print(f"==> {msg}", flush=True)


def write_config(model: str, embed_model: str) -> None:
    """Point DeepWiki at a config dir with our generator, embedder and repo
    settings. Must run before DeepWiki is imported: it reads them on import."""
    config = Path(tempfile.mkdtemp(prefix="deepwiki-config-"))
    generator = {
        "default_provider": "openrouter",
        "providers": {
            "openrouter": {
                "client_class": "OpenRouterClient",
                "default_model": model,
                "supportsCustomModel": True,
                "models": {model: {"temperature": 0.7}},
            }
        },
    }
    embedder = {
        "embedder": {
            "client_class": "OpenAIClient",
            "initialize_kwargs": {"base_url": OPENROUTER, "env_api_key_name": "OPENROUTER_API_KEY"},
            "batch_size": 32,
            "model_kwargs": {"model": embed_model, "encoding_format": "float"},
        },
        "retriever": {"top_k": 20},
        "text_splitter": {"split_by": "word", "chunk_size": 350, "chunk_overlap": 100},
    }
    # Upstream skips docs/, but most of this repo is docs (ADRs, research).
    # Skip docs/scratch and the wiki itself instead. DeepWiki matches an
    # excluded dir against a single path segment, hence "./wiki/".
    repo = json.loads((APP / "api/config/repo.json").read_text())
    dirs = repo["file_filters"]["excluded_dirs"]
    repo["file_filters"]["excluded_dirs"] = [d for d in dirs if d != "./docs/"] + ["./scratch/", "./wiki/"]
    repo["code_extensions"] = sorted({*repo["code_extensions"], ".sh", ".tf", ".tmpl", ".alloy", ".toml"})
    for name, data in (("generator.json", generator), ("embedder.json", embedder), ("repo.json", repo)):
        (config / name).write_text(json.dumps(data))
    os.environ["DEEPWIKI_CONFIG_DIR"] = str(config)
    # DeepWiki's default log file is under /app, which this user cannot write.
    os.environ.setdefault("LOG_FILE_PATH", str(Path.home() / "deepwiki.log"))


class LogCheck(logging.Handler):
    """DeepWiki only logs these failures and carries on with less context."""

    def __init__(self) -> None:
        super().__init__(logging.INFO)
        self.embedded = None  # (valid, total) from the last index build
        self.no_context = 0  # pages written without any retrieved source

    def emit(self, record: logging.LogRecord) -> None:
        msg = record.getMessage()
        if m := re.search(r"Embedding validation complete: (\d+)/(\d+)", msg):
            self.embedded = (int(m[1]), int(m[2]))
        elif "No documents retrieved from RAG" in msg:
            self.no_context += 1


def cited(page, changed: set[str]) -> bool:
    return any(path.removeprefix("./") in changed for path in page.filePaths)


async def generate(mode: str, model: str, previous: dict | None, changed: set[str]):
    """Return the wiki structure (pages with content) and the pages written now."""
    from api.rag import repo_index_exist
    from api.repository import Repo
    from api.schemas import WikiStructureModel, WikiTaskRequest
    from api.services.research import prepare_repo_index
    from api.services.wiki.tasks import WikiTask, _determine_structure, _generate_pages

    request = WikiTaskRequest(
        repo_url=str(REPO), type="local", provider="openrouter", model=model,
        language="en", owner="javatarz", repo="satat", comprehensive=True,
    )
    task = WikiTask.from_wiki_request(request)
    if mode == "full":
        structure = None
    else:
        structure = WikiStructureModel.model_validate(previous["structure"])
        todo = [p for p in structure.pages if cited(p, changed)]
        if not todo:
            return structure, []
        say(f"rewriting {len(todo)} of {len(structure.pages)} pages: {', '.join(p.id for p in todo)}")

    if not repo_index_exist(Repo(request.repo_url, request.type)):
        say("indexing the repo")
        await prepare_repo_index(request)
    if structure is None:
        say("planning the wiki structure")
        structure = await _determine_structure(task)
        todo = structure.pages
        say(f"writing {len(todo)} pages")

    task.wiki_structure = structure
    written = await _generate_pages(task, structure.model_copy(update={"pages": todo}))
    pages = [written.get(p.id, p) for p in structure.pages]
    return structure.model_copy(update={"pages": pages}), list(written.values())


def problems(structure, written, log: LogCheck, mode: str) -> list[str]:
    found = []
    for p in written:
        if m := FAILED_PAGE.match(p.content):
            found.append(f"page {p.id} failed: {p.content[m.start(2):][:160]!r}")
    for p in structure.pages:
        for path in p.filePaths:
            if not (REPO / path.removeprefix("./")).exists():
                hint = " (the structure is stale; run a full regeneration)" if mode == "diff" else ""
                found.append(f"page {p.id} cites a missing file: {path}{hint}")
    if log.embedded is None:
        found.append("no embedding validation in DeepWiki's log")
    elif log.embedded[0] != log.embedded[1]:
        found.append(f"only {log.embedded[0]}/{log.embedded[1]} chunks were embedded")
    if log.no_context:
        found.append(f"{log.no_context} page(s) were written without repo context (RAG retrieval failed)")
    return found


def slug(page_id: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", page_id.lower()).strip("-") or "page"


def write(path: Path, text: str) -> None:
    lines = [line.rstrip() for line in text.replace("\r\n", "\n").split("\n")]
    path.write_text("\n".join(lines).strip("\n") + "\n", encoding="utf-8")


def export(structure, commit: str, model: str) -> None:
    """Rebuild docs/wiki: index.md, one <page-id>.md per page, and wiki.json."""
    files = {p.id: f"{slug(p.id)}.md" for p in structure.pages}
    if len(set(files.values())) != len(files):
        die("page ids collide after slugging")
    titles = {p.id: p.title for p in structure.pages}
    for old in OUT.glob("*.md"):
        old.unlink()

    for p in structure.pages:
        body = p.content.strip()
        if not body.startswith("#"):
            body = f"# {p.title}\n\n{body}"
        related = [f"- [{titles[r]}]({files[r]})" for r in p.relatedPages if r in files and r != p.id]
        if related:
            body += "\n\n## Related pages\n\n" + "\n".join(related)
        write(OUT / files[p.id], f"{BANNER}\n\n[← Wiki index](index.md)\n\n{body}")

    sections = {s.id: s for s in structure.sections or []}
    toc, seen = [], set()

    def page_line(pid: str, depth: int) -> None:
        if pid in files and pid not in seen:
            seen.add(pid)
            toc.append(f"{'  ' * depth}- [{titles[pid]}]({files[pid]})")

    def section(sid: str, depth: int) -> None:
        if s := sections.get(sid):
            toc.append(f"{'  ' * depth}- **{s.title}**")
            for pid in s.pages:
                page_line(pid, depth + 1)
            for sub in s.subsections or []:
                section(sub, depth + 1)

    for sid in structure.rootSections or []:
        section(sid, 0)
    for p in structure.pages:  # pages outside every section
        page_line(p.id, 0)
    write(OUT / "index.md", f"{BANNER}\n\n# {structure.title}\n\n{structure.description}\n\n## Contents\n\n" + "\n".join(toc))

    state = {"commit": commit, "model": model, "structure": structure.model_dump()}
    STATE.write_text(json.dumps(state, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def main() -> None:
    mode = os.environ.get("WIKI_MODE", "diff")
    model, embed_model, commit = (os.environ[k] for k in ("WIKI_MODEL", "WIKI_EMBED_MODEL", "WIKI_COMMIT"))
    changed = set(filter(None, os.environ.get("WIKI_CHANGED", "").splitlines()))
    previous = json.loads(STATE.read_text()) if STATE.exists() else None
    if mode == "diff" and previous is None:
        die(f"no {STATE} to update; run a full regeneration")

    write_config(model, embed_model)
    sys.path.insert(0, str(APP))
    from api.logger import setup_logging

    setup_logging()
    log = LogCheck()
    logging.getLogger("deepwiki").addHandler(log)

    say(f"{mode} run: chat={model} embeddings={embed_model}")
    structure, written = asyncio.run(generate(mode, model, previous, changed))
    if not written:
        say("no page cites a changed file; the wiki is up to date")
        return
    if found := problems(structure, written, log, mode):
        die("the wiki was not written:\n  - " + "\n  - ".join(found))
    export(structure, commit, model)
    words = sum(len(p.content.split()) for p in structure.pages)
    say(f"wrote {len(written)} of {len(structure.pages)} pages ({words} words in the wiki) for {commit[:7]}")


if __name__ == "__main__":
    main()

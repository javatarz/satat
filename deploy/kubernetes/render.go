package kubernetes

import (
	"bytes"
	"fmt"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
	rbacv1 "k8s.io/api/rbac/v1"

	"github.com/javatarz/satat/config"
	"github.com/javatarz/satat/launcher"
	k8slauncher "github.com/javatarz/satat/launcher/kubernetes"
)

const (
	// PlatformPlaceholder is the image the render gives each lane's entry init container. The
	// platform image's digest changes with every build, so Up replaces it in memory with the
	// pushed reference before applying.
	PlatformPlaceholder = "satat-platform"

	// renderDir holds the rendered files, next to satat.yaml.
	renderDir  = "satat.k8s"
	valuesFile = renderDir + "/values.yaml"
	lanesFile  = renderDir + "/lanes.yaml"

	// Namespace is the platform's namespace: the chart's release and the platform Secrets.
	Namespace = "satat"
	// workerAccount is the worker's ServiceAccount (the chart's), bound by each lane's RoleBinding.
	workerAccount = "satat-worker"
	// probe is the address every lane's network policy must block: the API server, through the
	// kubernetes Service, which always has an endpoint. On k3d that endpoint is the node's IP in
	// 172.16.0.0/12, which no lane may reach. Where the API endpoint is a public IP an open lane can
	// reach it, so the probe never sees it blocked and every step fails closed after 30 s.
	probe = "kubernetes.default.svc.cluster.local:443"

	generated = "# Generated by satat deploy render from satat.yaml. Do not edit.\n"
)

// Render returns satat.k8s/values.yaml, the chart values that follow from satat.yaml, and
// satat.k8s/lanes.yaml, every lane's objects but its Secret. Neither holds a secret value.
func (t *Target) Render(cfg config.Config) (map[string][]byte, error) {
	values, err := marshal(map[string]any{
		"worker": map[string]any{"secretNames": config.WorkerSecrets},
	})
	if err != nil {
		return nil, err
	}
	var v bytes.Buffer
	v.WriteString(generated)
	v.WriteString("# Values for the chart in deploy/helm/satat. satat deploy up adds image.ref, worker.replicas\n")
	v.WriteString("# and config (satat.yaml itself) at install time.\n")
	v.Write(values)

	lanes := slices.Clone(cfg.Lanes)
	slices.SortFunc(lanes, func(a, b launcher.Lane) int { return strings.Compare(a.Name, b.Name) })
	opts := k8slauncher.LaneOptions{
		PlatformImage: PlatformPlaceholder,
		Probe:         probe,
		Worker:        rbacv1.Subject{Kind: rbacv1.ServiceAccountKind, Name: workerAccount, Namespace: Namespace},
	}
	var l bytes.Buffer
	l.WriteString(generated)
	l.WriteString("# Each lane's Namespace, SandboxTemplate, SandboxWarmPool and the worker's Role and RoleBinding,\n")
	l.WriteString("# applied by satat deploy up with image " + PlatformPlaceholder + " replaced by the pushed platform image.\n")
	l.WriteString("# Lane Secrets are not here: deploy up applies them from deploy.secrets.\n")
	for _, lane := range lanes {
		if lane.Image == PlatformPlaceholder {
			return nil, fmt.Errorf("lane %q: image %s is reserved for the platform image", lane.Name, PlatformPlaceholder)
		}
		objs, err := k8slauncher.LaneObjects(lane, opts)
		if err != nil {
			return nil, err
		}
		for _, o := range objs {
			doc, err := marshal(o.Object)
			if err != nil {
				return nil, fmt.Errorf("lane %q: %w", lane.Name, err)
			}
			l.WriteString("---\n")
			l.Write(doc)
		}
	}
	return map[string][]byte{valuesFile: v.Bytes(), lanesFile: l.Bytes()}, nil
}

// marshal is YAML with sorted keys and indented sequences, so a render is byte-stable and
// passes yamllint. Sorted keys put apiVersion, kind and metadata first in every object.
func marshal(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// withImage replaces the image line of each lane's entry init container, which the render sets
// to the placeholder, with ref. Only a line that is the image of a list item named entry under
// initContainers is replaced. It fails if a lane template has no such line, which would mean the
// render and this code disagree.
func withImage(lanes []byte, ref string) ([]byte, error) {
	lines := strings.SplitAfter(string(lanes), "\n")
	n := 0
	for i := range lines {
		if isEntryImage(lines, i) {
			body := strings.TrimRight(lines[i], "\n")
			lines[i] = body[:len(body)-len(PlatformPlaceholder)] + ref + lines[i][len(body):]
			n++
		}
	}
	if want := bytes.Count(lanes, []byte("\nkind: SandboxTemplate\n")); n != want {
		return nil, fmt.Errorf("%s has %d entry init container images to replace, want %d", lanesFile, n, want)
	}
	return []byte(strings.Join(lines, "")), nil
}

// isEntryImage says whether lines[i] is `image: satat-platform` in an initContainers item named
// entry. The render's YAML puts each key of an item at the same indent, the first after "- ".
func isEntryImage(lines []string, i int) bool {
	line := strings.TrimRight(lines[i], "\n")
	key := strings.TrimLeft(line, " ")
	indent := len(line) - len(key)
	if strings.HasPrefix(key, "- ") {
		key, indent = key[2:], indent+2
	}
	if key != "image: "+PlatformPlaceholder || indent < 2 {
		return false
	}
	pad := strings.Repeat(" ", indent)
	itemStart := strings.Repeat(" ", indent-2) + "- "
	// Back to the item's first line, then the key that holds the list.
	start := i
	for !strings.HasPrefix(lines[start], itemStart) {
		if start--; start < 0 || !strings.HasPrefix(lines[start], pad) && !strings.HasPrefix(lines[start], itemStart) {
			return false
		}
	}
	// Earlier items of the same list sit between the list's key and this item.
	owner := start - 1
	for owner >= 0 && (strings.HasPrefix(lines[owner], pad) || strings.HasPrefix(lines[owner], itemStart)) {
		owner--
	}
	if owner < 0 || strings.TrimSpace(lines[owner]) != "initContainers:" {
		return false
	}
	// The item's keys: its first line and every later line at its indent, until the item ends.
	for j := start; j < len(lines); j++ {
		l := strings.TrimRight(lines[j], "\n")
		if j > start && !strings.HasPrefix(l, pad) {
			break
		}
		if l == itemStart+"name: entry" || l == pad+"name: entry" {
			return true
		}
	}
	return false
}

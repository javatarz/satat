var update = flag.Bool("update", false, "rewrite the golden files in testdata")

func TestRenderGolden(t *testing.T) {
	cfg, err := config.Load("testdata/satat.yaml")
	if err != nil {
		t.Fatal(err)
	}
	first, err := (&Target{}).Render(cfg)
	if err != nil {
		t.Fatal(err)
	}
	second, err := (&Target{}).Render(cfg)
	if err != nil {
		t.Fatal(err)
	}
	if len(first) != 2 {
		t.Fatalf("Render returned %d files, want values.yaml and lanes.yaml", len(first))
	}
	for name, golden := range map[string]string{
		"satat.k8s/values.yaml": "testdata/values.yaml",
		"satat.k8s/lanes.yaml":  "testdata/lanes.yaml",
	} {
		got, ok := first[name]
		if !ok {
			t.Fatalf("Render has no %s", name)
		}
		if !bytes.Equal(got, second[name]) {
			t.Errorf("%s differs between two renders", name)
		}
		if !bytes.HasPrefix(got, []byte("# Generated by satat deploy render")) {
			t.Errorf("%s does not start with the generated header", name)
		}
		if *update {
			if err := os.WriteFile(golden, got, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		want, err := os.ReadFile(golden)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s differs from %s (go test ./deploy/kubernetes -run TestRenderGolden -update)", name, golden)
		}
	}
}

// Every object starts with apiVersion, kind and metadata, in lane-name order, and the init
// container's image is the placeholder Up replaces.
func TestRenderLanesShape(t *testing.T) {
	cfg, err := config.Load("testdata/satat.yaml")
	if err != nil {
		t.Fatal(err)
	}
	files, err := (&Target{}).Render(cfg)
	if err != nil {
		t.Fatal(err)
	}
	docs := strings.Split(string(files["satat.k8s/lanes.yaml"]), "\n---\n")
	var objs []string
	for _, d := range docs[1:] {
		lines := strings.SplitN(d, "\n", 4)
		if len(lines) < 3 || !strings.HasPrefix(lines[0], "apiVersion: ") || !strings.HasPrefix(lines[1], "kind: ") || lines[2] != "metadata:" {
			t.Fatalf("object does not start with apiVersion, kind, metadata:\n%s", d)
		}
		objs = append(objs, strings.TrimPrefix(lines[1], "kind: "))
	}
	want := "Namespace SandboxTemplate SandboxWarmPool Role RoleBinding"
	if got := strings.Join(objs, " "); got != want+" "+want {
		t.Errorf("objects = %s, want %s twice", got, want)
	}
	lanes := string(files["satat.k8s/lanes.yaml"])
	if strings.Index(lanes, "satat-lane-closed") > strings.Index(lanes, "satat-lane-open") {
		t.Error("lanes are not in name order")
	}
	if n := strings.Count(lanes, "image: "+PlatformPlaceholder+"\n"); n != 2 {
		t.Errorf("%d placeholder image lines, want one per lane", n)
	}
}

func TestRenderHasNoSecrets(t *testing.T) {
	t.Setenv("FOO", "TOPSECRET")
	t.Setenv("SATAT_GITHUB_TOKEN", "TOPSECRET")
	t.Setenv("SATAT_PUSH_TOKEN", "TOPSECRET")
	cfg, err := config.Load(filepath.Join("testdata", "satat.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	files, err := (&Target{}).Render(cfg)
	if err != nil {
		t.Fatal(err)
	}
	for name, data := range files {
		if bytes.Contains(data, []byte("TOPSECRET")) {
			t.Errorf("%s contains a secret value", name)
		}
		if bytes.Contains(data, []byte("kind: Secret")) {
			t.Errorf("%s contains a Secret", name)
		}
	}
}
